// ---------- Helper ----------
function sign(
  id: string,
  name: string,
  hindiName: string,
  category: SignCategory,
  description: string,
  handsCount: 1 | 2,
  handshapeDescription: string,
  movementDescription: string,
  difficulty: 'beginner' | 'intermediate' | 'advanced',
  iconEmoji: string,
  badgeColor: string,
  opts?: { facialExpressionNote?: string; culturalNote?: string },
): ISLSign {
  return {
    id,
    name,
    hindiName,
    category,
    description,
    handsCount,
    handshapeDescription,
    movementDescription,
    difficulty,
    iconEmoji,
    badgeColor,
    gestureTarget: id,
    hasGuideVideo: GUIDE_VIDEOS.has(id),
    facialExpressionNote: opts?.facialExpressionNote,
    culturalNote: opts?.culturalNote,
  };
}

